import importlib.util
from pathlib import Path

from bs4 import BeautifulSoup

ROOT = Path(__file__).resolve().parents[1]
MODULE_PATH = ROOT / "ci" / "customization" / "customize_doc.py"
SPEC = importlib.util.spec_from_file_location("customize_doc", MODULE_PATH)
customize_doc = importlib.util.module_from_spec(SPEC)
assert SPEC.loader is not None
SPEC.loader.exec_module(customize_doc)


def test_portal_api_index_is_skipped(tmp_path: Path) -> None:
    page = tmp_path / "api" / "index.html"
    page.parent.mkdir(parents=True)
    original = "<html><body>Portal API landing page</body></html>"
    page.write_text(original)

    customize_doc.customize_manifest_file(str(page))

    assert page.read_text() == original


def _customize(page: Path, project_name: str, version: str) -> BeautifulSoup:
    lib_map = {project_name: {"stable": f"/api/{project_name}/stable/", "nightly": None}}
    customize_doc.main(
        filepath=str(page),
        lib_path_dict=lib_map,
        project_name=project_name,
        versions_dict={"stable": version},
        selector_project_names={project_name},
    )
    return BeautifulSoup(page.read_text(), "html.parser")


def _assert_common_injections(soup: BeautifulSoup) -> None:
    assert soup.select_one("#rapids-selector-css")["href"] == "/assets/css/custom.css"
    assert soup.select_one("#rapids-selector-js")["src"] == "/assets/js/custom.js"
    assert soup.select_one("#rapids-selector-pixel-src") is not None
    assert soup.select_one("#rapids-selector-pixel-invocation") is not None


def test_doxygen_selector_injection(tmp_path: Path) -> None:
    page = tmp_path / "api" / "librmm" / "26.10" / "index.html"
    page.parent.mkdir(parents=True)
    page.write_text(
        """<!doctype html><html><head></head><body>
        <div id="titlearea"><table><tr><td>librmm</td></tr></table></div>
        <!-- Generated by Doxygen 1.9.1 --></body></html>"""
    )

    soup = _customize(page, "librmm", "26.10")
    assert soup.select_one("#rapids-doxygen-container") is not None
    assert soup.select_one("#titlearea > table") is None
    assert soup.select_one("#rapids-fa-tag") is not None
    _assert_common_injections(soup)

    first = page.read_text()
    _customize(page, "librmm", "26.10")
    assert page.read_text() == first


def test_pydata_selector_injection(tmp_path: Path) -> None:
    page = tmp_path / "api" / "ucxx" / "0.52" / "index.html"
    page.parent.mkdir(parents=True)
    page.write_text(
        """<!doctype html><html><head>
        <link rel="stylesheet" href="_static/styles/pydata-sphinx-theme.css">
        </head><body><div class="bd-sidebar"></div></body></html>"""
    )

    soup = _customize(page, "ucxx", "0.52")
    assert soup.select_one("#rapids-pydata-container") is not None
    assert soup.select_one("#rapids-fa-tag") is None
    _assert_common_injections(soup)

    first = page.read_text()
    _customize(page, "ucxx", "0.52")
    assert page.read_text() == first
